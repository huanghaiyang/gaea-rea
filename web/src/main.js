/**
 * main.js — Vue entry.
 *
 * The boot order matters and mirrors the old `app.js`:
 *
 *   1. localisation first, because it rewrites labels before anything renders
 *   2. the node catalogue, because the palette and every parameter form are built from it
 *   3. the extracted assets, because CLUTer and Halftone read them synchronously
 *
 * Steps 2 and 3 are independent, so they run together rather than in sequence.
 */
import { createApp } from 'vue';
import App from './App.vue';
import { initI18n } from '@js/i18n.js';
import { loadCatalog, state, selectedNode, viewNodes } from './stores/app.js';
import { startEvalReporting, loadDemo } from './stores/session.js';
import { preloadCLUTs, clutStatus } from '@js/clut.js';
import { preloadThresholds, thresholdStatus } from '@kernels/halftone.js';

/** Load the node catalogue. Distinguishes a file:// open from a real server failure. */
async function loadCatalogFromDisk() {
  if (location.protocol === 'file:') {
    throw new Error(
      'This page was opened as a file:// document, so fetch() is blocked. '
      + 'Run `npm run dev` and open the http:// URL it prints.',
    );
  }
  const res = await fetch('data/nodes.json', { cache: 'no-cache' });
  if (!res.ok) throw new Error(`data/nodes.json -> HTTP ${res.status}`);
  return res.json();
}

/**
 * Bring up the app.
 *
 * A missing vendor asset is NOT fatal: `web/assets` is gitignored and regenerated by
 * `tools/extract-assets.py`, so a clone that has not run it is an ordinary state. The affected
 * nodes fall back and the console says which, rather than the app refusing to start.
 */
async function boot() {
  await initI18n();

  const [catalog, clut, thresholds] = await Promise.all([
    loadCatalogFromDisk(),
    preloadCLUTs().catch((e) => ({ loaded: 0, failed: [String(e)] })),
    preloadThresholds().catch((e) => ({ loaded: 0, failed: [String(e)] })),
  ]);

  // From the store, not from state.js: only the store's wrapper also fills the `catalog` ref
  // that the palette's index is computed from. Importing the state layer's version here left
  // the palette empty while everything else rendered.
  loadCatalog(catalog);

  const warnings = [];
  if (clut.failed && clut.failed.length) {
    warnings.push(
      `${clut.failed.length} CLUT palette(s) unavailable: ${clut.failed.join(', ')}. `
      + 'Run tools/extract-assets.py to regenerate web/assets/.',
    );
  }
  if (!thresholds.loaded) {
    warnings.push(
      'No Halftone threshold maps; the ordered patterns will fall back to Floyd-Steinberg. '
      + 'Run tools/extract-magick.py.',
    );
  }

  // The evaluator's status and the field it produces are broadcast on the bus; this is what puts
  // them in the toolbar and hands the field to the viewport.
  startEvalReporting();

  const app = createApp(App);
  // Exposed for inspection and for the test harness, the same way the old shell exposed these.
  app.config.globalProperties.$clutStatus = clutStatus;
  app.config.globalProperties.$thresholdStatus = thresholdStatus;
  app.mount('#app');
  // Exposed for the headless probe: the diagnostic needs the store's values, not just the DOM.
  window.__store = { state, selectedNode, viewNodes };

  // AFTER mount: the demo is rendered by components that must already exist. Loading it before
  // `mount` would set the graph with no canvas to draw it on, which is how the first version came
  // up empty.
  try {
    loadDemo();
  } catch (e) {
    console.warn('[gaea] demo pipeline failed to load', e);
  }

  window.__gaea = {
    catalog,
    clut: clutStatus(),
    thresholds: thresholdStatus(),
    warnings,
  };

  // The overlay textures belong to the renderer inside `Viewport`, which is created lazily and may
  // not exist yet. So this is a GETTER rather than a snapshot: reading `window.__gaea.overlays`
  // always reflects the live renderer, and reports an empty list while there is none rather than
  // pretending the assets are missing.
  Object.defineProperty(window.__gaea, 'overlays', {
    enumerable: true,
    get() {
      const r3 = window.__viewportRenderer && window.__viewportRenderer();
      return r3 && r3.overlayStatus ? r3.overlayStatus() : [];
    },
  });
  for (const w of warnings) console.warn(`[gaea] ${w}`);
}

boot().catch((err) => {
  console.error('[gaea] boot failed', err);
  const el = document.getElementById('app');
  if (el) {
    // Rendered without Vue, because Vue is what failed to start.
    el.innerHTML = '';
    const box = document.createElement('div');
    box.style.cssText = 'font:14px/1.6 system-ui;padding:32px;color:#ddd;background:#1b1b1f;'
      + 'min-height:100vh;box-sizing:border-box';
    const h = document.createElement('h1');
    h.style.cssText = 'font-size:18px;margin:0 0 12px';
    h.textContent = 'Gaea REA failed to start';
    const p = document.createElement('pre');
    p.style.cssText = 'white-space:pre-wrap;color:#f88;margin:0';
    p.textContent = String(err && err.message ? err.message : err);
    box.append(h, p);
    el.appendChild(box);
  }
});
