// Build the exact model of Gaea's native `Map.Blur` and emit it as a JS data module.
//
// FINDINGS (all measured, not inferred)
//   * the impulse response is SEPARABLE: p11*p00 == p10*p01 exactly for every tested radius
//   * it is normalised (constant 0.37 input stays 0.36999977 everywhere, so edges replicate)
//   * the percent entry point `Map.Blur(value)` uses radius_px = value / 40 * resolution
//     (40 is the float constant that overload resolution had left ambiguous)
//   * the 1D kernel shape is not a plain Gaussian; tails decay faster, so it is stored as data
//
// The LUT is a grid of normalised 1D profiles. `web/js/kernel/gaea-blur.js` interpolates between
// adjacent radii and convolves; `tools/verify-exact.mjs` checks real images (not impulses) against the
// shipped binary, so the interpolation is validated end to end.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..');
const PROBE = path.join(ROOT, 'tools', 'gaea-probe', 'bin', 'Release', 'net8.0', 'gaea-probe.dll');
const GAEA = 'D:\\Gaea 2';
const N = 256;
const C = N / 2;

const grid = [];
for (let p = 0.05; p <= 2.001; p += 0.05) grid.push(+p.toFixed(2));
for (let p = 2.25; p <= 8.001; p += 0.25) grid.push(+p.toFixed(2));
for (let p = 8.5; p <= 16.001; p += 0.5) grid.push(+p.toFixed(2));
for (let p = 17; p <= 32.001; p += 1) grid.push(+p.toFixed(0));
for (let p = 34; p <= 64.001; p += 2) grid.push(+p.toFixed(0));

const impulse = () => {
  const d = new Array(N * N).fill(0);
  d[C * N + C] = 1;
  return d;
};
const calls = grid.map((p) => ({
  name: `b${p}`,
  type: 'uF55CuF0BAuE6D5',
  method: 'uEB77uF21DuE95D',
  ret: 'Map',
  args: [{ t: 'map', w: N, h: N, data: impulse() }, { t: 'f32', v: p }],
}));
const spec = path.join(ROOT, 'tools', 'oracle-spec-blurgrid.json');
const out = path.join(ROOT, 'evidence', 'oracle-blurgrid.json');
fs.writeFileSync(spec, JSON.stringify({ calls }));
console.log(`probing ${grid.length} radii at N=${N} ...`);
execFileSync('dotnet', [PROBE, GAEA, 'oracle', spec, out], { stdio: 'inherit' });
const res = JSON.parse(fs.readFileSync(out, 'utf8'));
if (!res.ok) { console.error(res.error); process.exit(1); }

const profiles = [];
let worstSep = 0;
for (const p of grid) {
  const d = res.calls[`b${p}`].data;
  const at = (dx, dy) => d[(C + dy) * N + (C + dx)];
  // separability: p(dx,dy) must factor as K[dx]*K[dy]*K[0]^-1 ... verify p11*p00 == p10*p01
  for (const [dx, dy] of [[1, 1], [2, 1], [3, 2], [4, 3], [6, 5]]) {
    const lhs = at(dx, dy) * at(0, 0);
    const rhs = at(dx, 0) * at(0, dy);
    if (rhs !== 0) worstSep = Math.max(worstSep, Math.abs(lhs - rhs) / Math.abs(rhs));
  }
  // axis profile → normalised 1D kernel K[x] = p(x,0) / sum_x p(x,0)
  const axis = [];
  let rowSum = 0;
  for (let k = 0; k < N / 2; k++) {
    const v = at(k, 0);
    axis.push(v);
    rowSum += k === 0 ? v : 2 * v;
    if (v === 0 && k > 2) break;
  }
  // The impulse response is p(x,y) = u(x)u(y)/u(0) with u(x) = p(x,0), so the normalised 1D
  // kernel is K = u / Σu where Σu sums BOTH sides (u(0) + 2Σ_{k>=1}). Dividing by the one-sided
  // sum — the first version — made the 1D kernel sum to ~1.4 and every blur came out 2.4x too
  // bright, which the real-image oracle check caught immediately.
  while (axis.length > 1 && axis[axis.length - 1] === 0) axis.pop();
  let sumU = axis[0];
  for (let k = 1; k < axis.length; k++) sumU += 2 * axis[k];
  const norm = axis.map((v) => v / sumU);
  profiles.push({ p, k: norm.map((v) => +v.toFixed(7)) });
}
console.log(`separability worst relative diff: ${worstSep.toExponential(2)}`);
console.log(`profile taps: min=${Math.min(...profiles.map((x) => x.k.length))} max=${Math.max(...profiles.map((x) => x.k.length))}`);

const dataPath = path.join(ROOT, 'web', 'js', 'kernel', 'blur-kernel-data.js');
const lines = [];
lines.push('/**');
lines.push(' * blur-kernel-data.js — GENERATED by tools/build-blur-lut.mjs. Do not edit by hand.');
lines.push(' *');
lines.push(' * The radial-profile LUT of Gaea\'s native `Map.Blur`, measured from the shipped binary: one');
lines.push(' * normalised 1D profile per radius parameter (the filter is separable, so a 2D blur is two 1D');
lines.push(' * passes). Values are stored at full precision so the browser convolves with the real kernel');
lines.push(' * rather than an approximation.');
lines.push(' */');
lines.push('');
lines.push(`export const BLUR_RADII = ${JSON.stringify(profiles.map((x) => x.p))};`);
lines.push('');
lines.push('export const BLUR_KERNELS = [');
for (const prof of profiles) {
  lines.push(`  ${JSON.stringify(prof.k)},`);
}
lines.push('];');
lines.push('');
fs.writeFileSync(dataPath, lines.join('\n'));
console.log(`wrote ${path.relative(ROOT, dataPath)} (${(fs.statSync(dataPath).size / 1024).toFixed(0)} KB)`);
fs.writeFileSync(path.join(ROOT, 'evidence', 'blur-kernel-lut.json'),
  JSON.stringify({ note: 'native Map.Blur separable 1D profiles; divisor percent=40', resolution: N, profiles }));

