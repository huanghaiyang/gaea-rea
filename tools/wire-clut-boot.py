#!/usr/bin/env python3
"""Wire the CLUT preload into the app's boot sequence."""
import pathlib
import sys

p = pathlib.Path(__file__).resolve().parent.parent / "web" / "js" / "app.js"
t = p.read_text(encoding="utf-8")

if "preloadCLUTs" in t:
    print("  already wired")
    sys.exit(0)

imp_anchor = "import { initI18n, setLang, currentLang, t } from './i18n.js';"
if imp_anchor not in t:
    print("  !! import anchor not found")
    sys.exit(1)
t = t.replace(imp_anchor, imp_anchor
              + "\nimport { preloadCLUTs, clutStatus } from './clut.js';")

# Insert right after initI18n(), before the catalog loads. The palettes are textures, so this is
# a set of HTTP fetches; doing it here means they are decoded by the time the first render asks
# for one, and the catalog load below overlaps with them.
boot_anchor = """    const catalog = await loadCatalogFromDisk();"""
if boot_anchor not in t:
    print("  !! boot anchor not found")
    sys.exit(1)

boot = """    // Gaea's eight built-in palette textures, decoded up front.
    //
    // CLUTer samples these synchronously, because every kernel here is synchronous, so the
    // textures have to be in the cache before a graph that uses the node is evaluated. This
    // awaits them rather than racing: on localhost they are ~2 MB of PNG and decode in well
    // under a frame's worth of user-visible time, and a race would show up as a graph that is
    // grey on its first evaluation and coloured on its second.
    //
    // A failure must NOT stop the app. The assets are gitignored vendor data regenerated by
    // `tools/extract-assets.py`, so a clone that has not run it is an ordinary state -- the
    // node falls back to a grey ramp and this reports which palettes are absent rather than
    // letting the UI come up silently desaturated.
    try {
      const clut = await preloadCLUTs();
      if (clut.failed.length) {
        console.warn(
          `[clut] ${clut.loaded} palettes loaded, ${clut.failed.length} unavailable: `
          + `${clut.failed.join(', ')}. Run tools/extract-assets.py to regenerate web/assets/.`,
        );
      }
      window.__clutStatus = clutStatus();
    } catch (e) {
      console.warn('[clut] preload failed; CLUTer will fall back to a grey ramp.', e);
    }

""" + boot_anchor

t = t.replace(boot_anchor, boot, 1)
p.write_text(t, encoding="utf-8")
print("  app.js: CLUT preload added to init()")
print("  exposed as window.__clutStatus for inspection")
